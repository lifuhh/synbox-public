import {
  BookmarkIcon,
  ChevronRightIcon,
  HistoryIcon,
  MusicIcon,
  SparklesIcon,
} from 'lucide-react'
import { Link } from 'react-router'

import { KaraokeEdge, KaraokeLabel } from '@/components/shared/karaoke-badge'
import type { SearchMatch } from '@/lib/offline/search'
import type { OfflineSong } from '@/lib/offline/song'
import { hasKaraoke } from '@/lib/offline/song'
import type { OfflineSource } from '@/lib/offline/sync'

const SOURCE_ICONS = {
  bookmark: { Icon: BookmarkIcon, label: 'Bookmarked' },
  mine: { Icon: SparklesIcon, label: 'Generated by you' },
  recent: { Icon: HistoryIcon, label: 'Opened recently' },
} as const satisfies Record<OfflineSource, unknown>

const SOURCE_ORDER: OfflineSource[] = ['mine', 'bookmark', 'recent']

const formatDate = (ms: number) =>
  new Date(ms).toLocaleDateString(undefined, {
    day: 'numeric',
    month: 'short',
    year:
      new Date(ms).getFullYear() === new Date().getFullYear()
        ? undefined
        : 'numeric',
  })

const Thumbnail = ({
  src,
  karaoke,
}: {
  src: string | null
  karaoke: boolean
}) => (
  <div className='relative aspect-video w-24 shrink-0 rounded bg-thumbnail-placeholder'>
    {src === null ? (
      <MusicIcon className='absolute inset-0 m-auto size-5 text-muted-foreground' />
    ) : (
      <img
        src={src}
        alt=''
        draggable={false}
        className='size-full rounded object-cover'
      />
    )}
    {karaoke && <KaraokeEdge />}
  </div>
)

export const OfflineSongRow = ({
  song,
  sources,
  sortAt,
  match,
}: {
  song: OfflineSong
  sources: Set<OfflineSource>
  sortAt: number
  match: SearchMatch | null
}) => (
  <li>
    <Link
      to={`/lyrics/${song.videoId}`}
      className='flex items-center gap-3 rounded-lg px-2 py-1.5 transition-colors hover:bg-accent active:bg-muted'>
      <Thumbnail src={song.thumbnail} karaoke={hasKaraoke(song)} />
      <div className='flex min-w-0 flex-1 flex-col'>
        <p className='line-clamp-2 text-sm leading-snug font-medium text-foreground'>
          {song.title}
          {hasKaraoke(song) && <KaraokeLabel />}
        </p>
        <p className='truncate text-xs text-muted-foreground'>{song.author}</p>
        {match?.kind === 'lyrics' ? (
          <p className='truncate text-xs text-primary-text italic'>
            “{match.line}”
          </p>
        ) : (
          <p className='flex items-center gap-1.5 text-xs text-muted-foreground'>
            <span>{formatDate(sortAt)}</span>
            {SOURCE_ORDER.filter((source) => sources.has(source)).map(
              (source) => {
                const { Icon, label } = SOURCE_ICONS[source]
                return (
                  <Icon
                    key={source}
                    aria-label={label}
                    className='size-3 shrink-0'
                  />
                )
              }
            )}
          </p>
        )}
      </div>
      <span className='flex shrink-0 items-center gap-0.5 text-sm text-muted-foreground'>
        <ChevronRightIcon aria-hidden='true' className='size-4' />
        <span className='sr-only'>View Lyrics</span>
      </span>
    </Link>
  </li>
)
