import {
  BookmarkIcon,
  ChevronRightIcon,
  HistoryIcon,
  MusicIcon,
  SparklesIcon,
} from 'lucide-react'
import { Link } from 'react-router'

import type { SearchMatch } from '@/lib/offline/search'
import type { OfflineSong } from '@/lib/offline/song'
import type { OfflineSource } from '@/lib/offline/sync'

const SOURCE_ICONS = {
  bookmark: { Icon: BookmarkIcon, label: 'Bookmarked' },
  mine: { Icon: SparklesIcon, label: 'Generated by you' },
  recent: { Icon: HistoryIcon, label: 'Opened recently' },
} as const satisfies Record<OfflineSource, unknown>

const SOURCE_ORDER: OfflineSource[] = ['mine', 'bookmark', 'recent']

const formatDate = (ms: number) =>
  new Date(ms).toLocaleDateString(undefined, {
    day: 'numeric',
    month: 'short',
    year:
      new Date(ms).getFullYear() === new Date().getFullYear()
        ? undefined
        : 'numeric',
  })

const Thumbnail = ({ src }: { src: string | null }) => (
  <div className='relative aspect-video w-28 shrink-0 overflow-hidden rounded-md bg-white/5 sm:w-32'>
    {src === null ? (
      <MusicIcon className='absolute inset-0 m-auto size-6 text-muted-foreground' />
    ) : (
      <img
        src={src}
        alt=''
        draggable={false}
        className='size-full object-cover'
      />
    )}
  </div>
)

export const OfflineSongRow = ({
  song,
  sources,
  sortAt,
  match,
}: {
  song: OfflineSong
  sources: Set<OfflineSource>
  sortAt: number
  match: SearchMatch | null
}) => (
  <li>
    <Link
      to={`/offline/${song.videoId}`}
      className='flex min-h-20 items-center gap-3 rounded-lg p-2 transition-colors hover:bg-white/5 active:bg-white/10'>
      <Thumbnail src={song.thumbnail} />
      <div className='flex min-w-0 flex-1 flex-col gap-0.5'>
        <p className='line-clamp-2 text-label leading-snug font-semibold text-foreground'>
          {song.title}
        </p>
        <p className='truncate text-sm text-muted-foreground'>{song.author}</p>
        {match?.kind === 'lyrics' ? (
          <p className='truncate text-xs text-primary italic'>“{match.line}”</p>
        ) : (
          <p className='flex items-center gap-1.5 text-xs text-muted-foreground'>
            <span>{formatDate(sortAt)}</span>
            {SOURCE_ORDER.filter((source) => sources.has(source)).map(
              (source) => {
                const { Icon, label } = SOURCE_ICONS[source]
                return (
                  <Icon
                    key={source}
                    aria-label={label}
                    className='size-3.5 shrink-0'
                  />
                )
              }
            )}
          </p>
        )}
      </div>
      <span className='flex shrink-0 items-center gap-0.5 text-sm text-muted-foreground'>
        <span className='hidden sm:inline'>View Lyrics</span>
        <ChevronRightIcon aria-hidden='true' className='size-5' />
        <span className='sr-only sm:hidden'>View Lyrics</span>
      </span>
    </Link>
  </li>
)
